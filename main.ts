// Obsidian's v3 MathJax lazily `autoload`s extensions the first time a command
// is used. Our v4 engine renders synchronously and can't autoload, so we instead
// pre-activate that same set (plus mathtools for \coloneqq & friends). Packages
// a preamble \require{}s are added on top (see loadPreamble). Note: physics,
// upgreek, etc. change parsing semantics, so they stay opt-in via \require.
const TEX_PACKAGES = [
	"base",
	"ams",
	"newcommand",
	"configmacros",
	"noundefined",
	"textmacros",
	// mathtools: \coloneqq, \eqqcolon, \xrightarrow, \prescript, …
	"mathtools",
	// the packages Obsidian v3 autoloaded on demand:
	"action",
	"amscd",
	"bbox",
	"boldsymbol",
	"braket",
	"bussproofs",
	"cancel",
	"color",
	"enclose",
	"extpfeil",
	"html",
	"mhchem",
	"unicode",
	"verb",
];

type DisplayOverflow = "linebreak" | "scale" | "scroll" | "overflow";
type DisplayAlign = "left" | "center" | "right";

interface MathJaxPlusSettings {
	preamblePath: string;
	font: string;
	displayOverflow: DisplayOverflow;
	breakWidth: string;
	displayAlign: DisplayAlign;
	preferRelationBreaks: boolean;
}

const DEFAULT_SETTINGS: MathJaxPlusSettings = {
	// Same default + key as the Extended MathJax plugin, so it's a drop-in.
	preamblePath: "preamble.sty",
	font: DEFAULT_FONT,
	displayOverflow: "linebreak",
	breakWidth: "100%",
	displayAlign: "center",
	preferRelationBreaks: true,
};

// \require[opt]{name} — capture group is the package name.
const REQUIRE_RE = /\\require(?:\[[^\]]*\])?\{([^}]+)\}/g;

// Strengthen MathJax's preference for breaking long display equations at
// relations (=, ≤, →) and binary operators (+, −) rather than mid-expression.
// MathJax's break penalty is (line-fullness ≈ up to 2500) + (class bonus); the
// default bonuses (REL −500 / BIN −250) are too weak, so breaking at "=" — which
// leaves a short, "underfull" first line — loses to filling past it. We boost the
// bonuses so a nearby relation/operator wins.
// (LinebreakVisitor has 12 type params; an untyped base keeps the subclass simple.)
const BaseLinebreakVisitor = LinebreakVisitor as unknown as {
	// eslint-disable-next-line @typescript-eslint/no-explicit-any
	new (...args: any[]): { TEXCLASS: Record<number, (p: number) => number> };
};
class RelationLinebreakVisitor extends BaseLinebreakVisitor {
	// eslint-disable-next-line @typescript-eslint/no-explicit-any
	constructor(...args: any[]) {
		super(...args);
		this.TEXCLASS = {
			[TEXCLASS.BIN]: (p: number) => p - 750,
			[TEXCLASS.REL]: (p: number) => p - 1500,
		};
	}
}

// Rewrite the generated @font-face url("mjxfonts/<file>.woff2") references to the
// active font's bundled data URIs, preserving MathJax's own @font-face descriptors
// (metrics). Idempotent: once rewritten the url() no longer matches.
const FONT_URL_RE = /url\((["']?)mjxfonts\/([^"')]+\.woff2)\1\)/g;
function inlineFonts(
	el: HTMLStyleElement,
	data: Record<string, string>,
): HTMLStyleElement {
	const swap = (s: string) =>
		s.replace(FONT_URL_RE, (m, _q, f) => (data[f] ? `url(${data[f]})` : m));
	if (el.textContent && el.textContent.includes("mjxfonts/")) {
		el.textContent = swap(el.textContent);
		return el;
	}
	// adaptiveCSS inserts rules into el.sheet rather than textContent.
	const sheet = el.sheet;
	if (sheet) {
		for (let i = 0; i < sheet.cssRules.length; i++) {
			const r = sheet.cssRules[i];
			if (r instanceof CSSFontFaceRule && r.cssText.includes("mjxfonts/")) {
				const text = swap(r.cssText);
				sheet.deleteRule(i);
				sheet.insertRule(text, i);
			}
		}
	}
	return el;
}

// The four global hooks Obsidian's renderMath()/finishRenderMath() and other
// plugins call. We swap them to route through v4, and restore on unload.
interface MathJaxGlobal {
	tex2chtml?: (source: string, options?: { display?: boolean }) => HTMLElement;
	tex2chtmlPromise?: (
		source: string,
		options?: { display?: boolean },
	) => Promise<HTMLElement>;
	chtmlStylesheet?: () => HTMLElement;
	startup?: { document?: unknown };
}

export default class MathJaxPlusPlugin extends Plugin {
	settings: MathJaxPlusSettings = DEFAULT_SETTINGS;
	private saved: Partial<MathJaxGlobal> = {};
	private savedDocument: unknown;
	private patched = false;
	private handlerRegistered = false;
	/** Preamble source with \require lines stripped, ready to register. */
	private preambleSrc = "";
	/** Package names parsed from the preamble's \require directives. */
	private requiredPackages: string[] = [];
	/** Current output jax — its options are mutated for live overflow/align. */
	private chtml: InstanceType<typeof CHTML> | null = null;

	async onload() {
		await this.loadSettings();
		this.addSettingTab(new MathJaxPlusSettingTab(this.app, this));

		// Ensure Obsidian has created its (v3) MathJax global + CSS scaffolding.
		await loadMathJax();

		const mj = (window as unknown as { MathJax?: MathJaxGlobal }).MathJax;
		if (!mj) {
			console.error("[mathjax-plus] window.MathJax not present after loadMathJax()");
			return;
		}

		// Make font-chunk loading synchronous. The chunks are already bundled (per
		// font), so asyncLoad is a no-op; loadDynamicFilesSync then defines every
		// glyph's metrics up front so synchronous getChar never retries.
		mathjax.asyncIsSynchronous = true;
		mathjax.asyncLoad = () => undefined;

		// Read the preamble first: the packages it \require{}s must be active when
		// the TeX jax is constructed.
		this.requiredPackages = await this.loadPreamble();

		this.buildEngine();
		console.log("[mathjax-plus] MathJax v4 engine installed");
	}

	/**
	 * Build (or rebuild) the v4 engine from current settings and swap it into the
	 * global hooks. Called on load and whenever the font changes. Pass `rebuild`
	 * when changing the font at runtime so open notes fully re-render.
	 */
	buildEngine(rebuild = false) {
		const mj = (window as unknown as { MathJax?: MathJaxGlobal }).MathJax;
		if (!mj) return;

		if (!this.handlerRegistered) {
			RegisterHTMLHandler(browserAdaptor());
			this.handlerRegistered = true;
		}

		const entry: FontEntry = FONTS[this.settings.font] ?? FONTS[DEFAULT_FONT];
		const tex = new TeX({
			packages: [...new Set([...TEX_PACKAGES, ...this.requiredPackages])],
		});
		const chtml = new CHTML({
			fontData: entry.FontClass,
			// Sentinel base: the generated @font-face url()s become
			// "mjxfonts/<file>.woff2", which inlineFonts() rewrites to data URIs.
			fontURL: "mjxfonts",
			displayOverflow: this.settings.displayOverflow,
			linebreaks: {
				inline: true,
				width: this.settings.breakWidth,
				lineleading: 0.2,
				...(this.settings.preferRelationBreaks
					? { LinebreakVisitor: RelationLinebreakVisitor }
					: {}),
			},
			displayAlign: this.settings.displayAlign,
		});
		this.chtml = chtml;
		const doc = mathjax.document(document, { InputJax: tex, OutputJax: chtml });

		// Load all glyph metrics now so synchronous conversion has every char.
		chtml.font.loadDynamicFilesSync();

		// Register the preamble's macros on this engine (persist across renders).
		if (this.preambleSrc.trim()) {
			try {
				doc.convert(this.preambleSrc, { end: STATE.COMPILED });
			} catch (e) {
				const msg = e instanceof Error ? e.message : String(e);
				new Notice(`MathJax Plus: preamble error — ${msg}`);
				console.error("[mathjax-plus] preamble error", e);
			}
		}

		// Capture the v3 hooks once, before our first overwrite.
		if (!this.patched) {
			this.saved.tex2chtml = mj.tex2chtml;
			this.saved.tex2chtmlPromise = mj.tex2chtmlPromise;
			this.saved.chtmlStylesheet = mj.chtmlStylesheet;
			this.savedDocument = mj.startup?.document;
		}

		const convert = (source: string, options?: { display?: boolean }) =>
			doc.convert(source, { display: !!options?.display }) as HTMLElement;

		mj.tex2chtml = convert;
		mj.tex2chtmlPromise = (source, options) =>
			Promise.resolve(convert(source, options));
		mj.chtmlStylesheet = () =>
			inlineFonts(
				chtml.styleSheet(doc) as unknown as HTMLStyleElement,
				entry.data,
			) as unknown as HTMLElement;
		if (mj.startup) mj.startup.document = doc;
		this.patched = true;

		this.reRender(rebuild);
	}

	/**
	 * Apply overflow/width/alignment changes without rebuilding the engine — these
	 * are output-jax options read at typeset time, so mutating them + re-rendering
	 * is enough (and avoids reloading font metrics).
	 */
	applyOutputOptions(rebuild = false) {
		if (!this.chtml) return;
		this.chtml.options.displayOverflow = this.settings.displayOverflow;
		this.chtml.options.displayAlign = this.settings.displayAlign;
		this.chtml.options.linebreaks.width = this.settings.breakWidth;
		this.reRender(rebuild);
	}

	/**
	 * Inject the current stylesheet and refresh open notes. Pass `rebuild` after a
	 * font change: the new font uses different CSS classes, so already-rendered
	 * math (esp. in Live Preview, which previewMode.rerender doesn't touch) must be
	 * fully rebuilt — the programmatic equivalent of closing and reopening the note.
	 */
	private reRender(rebuild = false) {
		finishRenderMath();
		this.app.workspace.iterateAllLeaves((leaf) => {
			const view = leaf.view;
			if (!(view instanceof MarkdownView)) return;
			const rebuildView = (leaf as { rebuildView?: () => void }).rebuildView;
			if (rebuild && typeof rebuildView === "function") {
				rebuildView.call(leaf); // re-renders both Reading view and Live Preview
			} else {
				view.previewMode?.rerender(true);
			}
		});
	}

	onunload() {
		if (!this.patched) return;
		const mj = (window as unknown as { MathJax?: MathJaxGlobal }).MathJax;
		if (mj) {
			mj.tex2chtml = this.saved.tex2chtml;
			mj.tex2chtmlPromise = this.saved.tex2chtmlPromise;
			mj.chtmlStylesheet = this.saved.chtmlStylesheet;
			if (mj.startup) mj.startup.document = this.savedDocument;
		}
		// Reverting to v3 also changes the math CSS classes, so fully rebuild.
		this.reRender(true);
	}

	/**
	 * Read the configured preamble file, parse its `\require{...}` directives, and
	 * stash the source with those directives stripped (in `preambleSrc`). `\require`
	 * forces an async package load our synchronous convert can't do, so instead we
	 * return the package names to activate up front via the TeX `packages` list.
	 */
	private async loadPreamble(): Promise<string[]> {
		const path = this.settings.preamblePath?.trim();
		this.preambleSrc = "";
		if (!path) return [];
		const adapter = this.app.vault.adapter;
		if (!(await adapter.exists(path))) return [];
		try {
			const src = await adapter.read(path);
			const required = [...src.matchAll(REQUIRE_RE)].map((m) => m[1].trim());
			this.preambleSrc = src.replace(REQUIRE_RE, "");
			return required;
		} catch (e) {
			new Notice(`MathJax Plus: could not read preamble "${path}"`);
			console.error("[mathjax-plus] preamble read error", e);
			return [];
		}
	}

	async loadSettings() {
		this.settings = Object.assign({}, DEFAULT_SETTINGS, await this.loadData());
	}

	async saveSettings() {
		await this.saveData(this.settings);
	}
}

class MathJaxPlusSettingTab extends PluginSettingTab {
	constructor(
		app: MathJaxPlusSettingTab["app"],
		private plugin: MathJaxPlusPlugin,
	) {
		super(app, plugin);
	}

	display() {
		const { containerEl } = this;
		const plugin = this.plugin;
		containerEl.empty();

		new Setting(containerEl).setName("Rendering").setHeading();

		new Setting(containerEl)
			.setName("Math font")
			.setDesc("The MathJax v4 font used to render all math.")
			.addDropdown((dd) => {
				for (const [key, entry] of Object.entries(FONTS)) dd.addOption(key, entry.label);
				dd.setValue(plugin.settings.font).onChange(async (value) => {
					plugin.settings.font = value;
					await plugin.saveSettings();
					// Rebuild engine + fully re-render open notes (font CSS changes).
					plugin.buildEngine(true);
				});
			});

		new Setting(containerEl)
			.setName("Wide display equations")
			.setDesc(
				"How to handle display equations too wide for the note: line-break, scale to fit, scroll, or let them overflow.",
			)
			.addDropdown((dd) => {
				dd.addOptions({
					linebreak: "Line-break",
					scale: "Scale to fit",
					scroll: "Scroll",
					overflow: "Overflow",
				})
					.setValue(plugin.settings.displayOverflow)
					.onChange(async (value) => {
						plugin.settings.displayOverflow = value as DisplayOverflow;
						await plugin.saveSettings();
						plugin.applyOutputOptions(true);
					});
			});

		new Setting(containerEl)
			.setName("Line-break width")
			.setDesc(
				'Wrap width for line-breaking, as a percentage of the note width or a fixed size (e.g. "100%", "80%", "30em").',
			)
			.addText((text) =>
				text
					.setPlaceholder("100%")
					.setValue(plugin.settings.breakWidth)
					.onChange(async (value) => {
						plugin.settings.breakWidth = value.trim() || "100%";
						await plugin.saveSettings();
						plugin.applyOutputOptions();
					}),
			);

		new Setting(containerEl)
			.setName("Display alignment")
			.setDesc("Horizontal alignment of display equations.")
			.addDropdown((dd) => {
				dd.addOptions({ left: "Left", center: "Center", right: "Right" })
					.setValue(plugin.settings.displayAlign)
					.onChange(async (value) => {
						plugin.settings.displayAlign = value as DisplayAlign;
						await plugin.saveSettings();
						plugin.applyOutputOptions(true);
					});
			});

		new Setting(containerEl)
			.setName("Prefer breaks at relations")
			.setDesc(
				"When auto-breaking wide equations, strongly prefer breaking at relations (=, ≤) and operators (+, −) rather than mid-expression. Turn off for MathJax's default balancing.",
			)
			.addToggle((tg) =>
				tg.setValue(plugin.settings.preferRelationBreaks).onChange(async (value) => {
					plugin.settings.preferRelationBreaks = value;
					await plugin.saveSettings();
					plugin.buildEngine(true); // visitor is set at engine construction
				}),
			);

		new Setting(containerEl).setName("Preamble").setHeading();

		new Setting(containerEl)
			.setName("Preamble file")
			.setDesc(
				"Vault-relative path to a .sty file of \\newcommand macros loaded into MathJax. Reload Obsidian after changing the preamble or this path.",
			)
			.addText((text) =>
				text
					.setPlaceholder("preamble.sty")
					.setValue(plugin.settings.preamblePath)
					.onChange(async (value) => {
						plugin.settings.preamblePath = value;
						await plugin.saveSettings();
					}),
			);
	}
}
