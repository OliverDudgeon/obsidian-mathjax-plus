// Regenerates tex-extensions.ts: side-effect imports of every TeX extension
// Configuration so any package named in a preamble's \require{...} is registered
// and can be activated synchronously (no async loader needed).
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const srcPkg = dirname(require.resolve("@mathjax/src/package.json"));
const texDir = join(srcPkg, "mjs", "input", "tex");

// Each extension lives in its own subdir with a *Configuration.js file.
const mods = [];
for (const name of readdirSync(texDir).sort()) {
	const sub = join(texDir, name);
	if (!statSync(sub).isDirectory()) continue;
	const cfg = readdirSync(sub).find((f) => /Configuration\.js$/.test(f));
	if (cfg) mods.push(`${name}/${cfg}`);
}

const body =
	"// AUTO-GENERATED by scripts/gen-tex-extensions.mjs — registers every TeX\n" +
	"// extension so preamble \\require{...} resolves synchronously.\n" +
	mods.map((m) => `import "@mathjax/src/js/input/tex/${m}";`).join("\n") +
	"\n";
writeFileSync(new URL("../tex-extensions.ts", import.meta.url), body);
console.log("wrote tex-extensions.ts:", mods.length, "extensions");
