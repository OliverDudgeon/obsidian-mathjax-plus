// Generates per-font modules (fonts/<key>.ts) and font-registry.ts for the
// curated set of v4 fonts. Each font module side-effect-imports its dynamic
// glyph chunks and inlines its woff2 as base64 data URIs (esbuild dataurl
// loader), so any selectable font is fully self-contained in the single main.js.
import { readdirSync, writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);

// key -> npm package short name. Order = display order in the picker.
const FONTS = [
	["newcm", "newcm", "New Computer Modern"],
	["stix2", "stix2", "STIX Two"],
	["tex", "tex", "TeX (classic MathJax)"],
	["pagella", "pagella", "TeX Gyre Pagella"],
	["fira", "fira", "Fira Math (sans-serif)"],
];

mkdirSync(new URL("../fonts", import.meta.url), { recursive: true });

for (const [key, pkg] of FONTS) {
	const pkgName = `@mathjax/mathjax-${pkg}-font`;
	const root = dirname(require.resolve(`${pkgName}/package.json`));
	const cls = readFileSync(join(root, "mjs", "chtml.js"), "utf8").match(
		/export class (MathJax\w+Font)/,
	)[1];
	const chunks = (() => {
		try {
			return readdirSync(join(root, "mjs", "chtml", "dynamic"))
				.filter((f) => f.endsWith(".js"))
				.sort();
		} catch {
			return [];
		}
	})();
	const woff2 = readdirSync(join(root, "chtml", "woff2"))
		.filter((f) => f.endsWith(".woff2"))
		.sort();

	let out = `// AUTO-GENERATED by scripts/gen-fonts.mjs — font "${key}".\n`;
	out += `import { ${cls} } from "${pkgName}/js/chtml.js";\n`;
	for (const c of chunks) out += `import "${pkgName}/js/chtml/dynamic/${c}";\n`;
	woff2.forEach((f, i) => (out += `import w${i} from "${pkgName}/chtml/woff2/${f}";\n`));
	out += `\nexport const FontClass = ${cls};\n`;
	out += `export const FONT_DATA: Record<string, string> = {\n`;
	woff2.forEach((f, i) => (out += `\t"${f}": w${i},\n`));
	out += `};\n`;
	writeFileSync(new URL(`../fonts/${key}.ts`, import.meta.url), out);
	console.log(`fonts/${key}.ts: ${cls}, ${chunks.length} chunks, ${woff2.length} woff2`);
}

// Registry
let reg = "// AUTO-GENERATED by scripts/gen-fonts.mjs.\n";
FONTS.forEach(([key]) => {
	reg += `import { FontClass as C_${key}, FONT_DATA as D_${key} } from "./fonts/${key}";\n`;
});
reg += `\nexport interface FontEntry {\n\tlabel: string;\n\t// eslint-disable-next-line @typescript-eslint/no-explicit-any\n\tFontClass: any;\n\tdata: Record<string, string>;\n}\n\n`;
reg += `export const DEFAULT_FONT = "${FONTS[0][0]}";\n\n`;
reg += `export const FONTS: Record<string, FontEntry> = {\n`;
FONTS.forEach(([key, , label]) => {
	reg += `\t${key}: { label: ${JSON.stringify(label)}, FontClass: C_${key}, data: D_${key} },\n`;
});
reg += `};\n`;
writeFileSync(new URL("../font-registry.ts", import.meta.url), reg);
console.log(`font-registry.ts: ${FONTS.length} fonts`);
